/** Grid -> path SVG tunggal (run-length per baris supaya ringan). */
function gridToPath(rows) {
  let path = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x += 1;
        continue;
      }
      let run = 1;
      while (row[x + run] === '#') run += 1;
      path += `M${x} ${y}h${run}v1h-${run}z`;
      x += run;
    }
  });
  return path;
}

const PATHS = Object.fromEntries(Object.entries(GRIDS).map(([name, rows]) => [name, gridToPath(rows)]));

/**
 * @param {string} name   nama ikon (lihat GRIDS)
 * @param {{size?: number|string, label?: string, className?: string}} [options]
 *        label diisi -> ikon diumumkan pembaca layar; kosong -> disembunyikan (dekoratif)
 */
export function icon(name, { size = 16, label = '', className = '' } = {}) {
  const path = PATHS[name] ?? PATHS.star;
  const accessibility = label ? `role="img" aria-label="${label.replace(/"/g, '&quot;')}"` : 'aria-hidden="true"';
  return raw(
    `<svg class="pixel-icon ${className}" viewBox="0 0 10 10" width="${size}" height="${size}" fill="currentColor" shape-rendering="crispEdges" focusable="false" ${accessibility}><path d="${path}"/></svg>`,
  );
}

